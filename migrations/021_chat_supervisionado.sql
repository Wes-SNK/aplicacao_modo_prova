-- 021 - Comunicação supervisionada opcional para a sala de espera.
-- STAGING: não aplicar ao Supabase de produção antes da homologação.
-- Nenhuma tabela existente é alterada. Nunca expor as tabelas ao papel anon.
CREATE TABLE IF NOT EXISTS public.exam_lobby_chat_settings (
 exam_id uuid PRIMARY KEY REFERENCES public.exams(id) ON DELETE CASCADE,
 enabled boolean NOT NULL DEFAULT false,
 peer_messages boolean NOT NULL DEFAULT false,
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.exam_lobby_chat_mutes (
 exam_id uuid NOT NULL REFERENCES public.exams(id) ON DELETE CASCADE,
 student_id uuid NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
 muted boolean NOT NULL DEFAULT true,
 PRIMARY KEY (exam_id,student_id)
);
CREATE TABLE IF NOT EXISTS public.exam_lobby_chat_messages (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 exam_id uuid NOT NULL REFERENCES public.exams(id) ON DELETE CASCADE,
 sender_student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
 recipient_student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
 teacher_sender boolean NOT NULL DEFAULT false,
 teacher_only boolean NOT NULL DEFAULT false,
 body text NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 150),
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK ((teacher_sender AND sender_student_id IS NULL) OR
        (NOT teacher_sender AND sender_student_id IS NOT NULL)),
 CHECK (recipient_student_id IS DISTINCT FROM sender_student_id)
);
CREATE INDEX IF NOT EXISTS exam_lobby_chat_recent
 ON public.exam_lobby_chat_messages(exam_id,id DESC);
CREATE INDEX IF NOT EXISTS exam_lobby_chat_sender_rate
 ON public.exam_lobby_chat_messages(exam_id,sender_student_id,created_at DESC);

ALTER TABLE public.exam_lobby_chat_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exam_lobby_chat_mutes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exam_lobby_chat_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.exam_lobby_chat_settings,public.exam_lobby_chat_mutes,
 public.exam_lobby_chat_messages FROM PUBLIC,anon,authenticated;

-- Sender and receiver are returned as anonymous handles to other students.
-- Real names remain visible only in the authenticated professor roster.
CREATE OR REPLACE FUNCTION public.student_lobby_chat_read(
 p_lobby_token uuid,p_after bigint DEFAULT 0
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='public'
AS $fn$
DECLARE v_lobby public.exam_lobby;v_setting public.exam_lobby_chat_settings;
 v_peers jsonb;v_messages jsonb;v_muted boolean;v_allowed boolean;
BEGIN
 SELECT * INTO v_lobby FROM public.exam_lobby WHERE lobby_token=p_lobby_token;
 IF NOT FOUND THEN RAISE EXCEPTION 'Sessão inválida'; END IF;
 SELECT * INTO v_setting FROM public.exam_lobby_chat_settings
 WHERE exam_id=v_lobby.exam_id;
 v_allowed:=coalesce(v_setting.enabled,false) AND NOT EXISTS(
   SELECT 1 FROM public.attempts
   WHERE exam_id=v_lobby.exam_id AND student_id=v_lobby.student_id
 );
 SELECT coalesce(muted,false) INTO v_muted FROM public.exam_lobby_chat_mutes
 WHERE exam_id=v_lobby.exam_id AND student_id=v_lobby.student_id;
 SELECT coalesce(jsonb_agg(jsonb_build_object(
   'id',substr(md5(l.student_id::text),1,10),'handle','Colega-'||upper(substr(md5(l.student_id::text),1,4)),
   'self',l.student_id=v_lobby.student_id
 ) ORDER BY l.student_id),'[]'::jsonb) INTO v_peers
 FROM public.exam_lobby l JOIN public.students s ON s.id=l.student_id
 WHERE l.exam_id=v_lobby.exam_id AND s.active AND
 l.last_seen_at>now()-interval '45 seconds' AND l.requested_at IS NOT NULL
 AND NOT EXISTS(SELECT 1 FROM public.attempts a
  WHERE a.exam_id=l.exam_id AND a.student_id=l.student_id);
 SELECT coalesce(jsonb_agg(to_jsonb(msg) ORDER BY msg.id),'[]'::jsonb)
 INTO v_messages
 FROM (
  SELECT m.id,m.body,m.created_at,m.teacher_sender,
   CASE WHEN m.teacher_sender THEN 'Professor'
     ELSE 'Colega-'||upper(substr(md5(m.sender_student_id::text),1,4)) END AS sender,
   m.sender_student_id=v_lobby.student_id AS self,
   CASE WHEN m.recipient_student_id IS NULL THEN 'Todos'
     WHEN m.recipient_student_id=v_lobby.student_id THEN 'Você'
     ELSE 'Colega-'||upper(substr(md5(m.recipient_student_id::text),1,4)) END AS recipient
  FROM public.exam_lobby_chat_messages m
  WHERE m.exam_id=v_lobby.exam_id
    AND m.id>greatest(0,coalesce(p_after,0))
    AND v_allowed AND (
     (m.teacher_only AND m.sender_student_id=v_lobby.student_id) OR
     (NOT m.teacher_only AND
      (m.recipient_student_id IS NULL OR
       m.sender_student_id=v_lobby.student_id OR
       m.recipient_student_id=v_lobby.student_id)))
    AND v_allowed
  ORDER BY m.id DESC LIMIT 40
 ) msg;
 RETURN jsonb_build_object('enabled',v_allowed,'peer_messages',
   coalesce(v_setting.peer_messages,false),'muted',coalesce(v_muted,false),
   'messages',v_messages,'peers',CASE WHEN v_allowed THEN v_peers ELSE '[]'::jsonb END);
END;
$fn$;

CREATE OR REPLACE FUNCTION public.student_lobby_chat_send(
 p_lobby_token uuid,p_body text,p_recipient text DEFAULT NULL,
 p_teacher_only boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='public'
AS $fn$
DECLARE l public.exam_lobby;c public.exam_lobby_chat_settings;
 v_text text;v_id bigint;v_recipient uuid;
BEGIN
 SELECT * INTO l FROM public.exam_lobby WHERE lobby_token=p_lobby_token;
 IF NOT FOUND THEN RAISE EXCEPTION 'Sessão inválida';END IF;
 SELECT * INTO c FROM public.exam_lobby_chat_settings WHERE exam_id=l.exam_id;
 IF NOT coalesce(c.enabled,false) THEN RAISE EXCEPTION 'Mensagens desativadas';END IF;
 IF EXISTS(SELECT 1 FROM public.attempts a
  WHERE a.exam_id=l.exam_id AND a.student_id=l.student_id) THEN
  RAISE EXCEPTION 'Mensagens indisponíveis após ingresso na avaliação';END IF;
 IF EXISTS(SELECT 1 FROM public.exam_lobby_chat_mutes m WHERE
   m.exam_id=l.exam_id AND m.student_id=l.student_id AND m.muted)
 THEN RAISE EXCEPTION 'Envio de mensagens suspenso';END IF;
 v_text:=btrim(coalesce(p_body,''));
 IF char_length(v_text) NOT BETWEEN 1 AND 150 OR
  v_text~'[\x00-\x08\x0B\x0C\x0E-\x1F]' THEN
  RAISE EXCEPTION 'Mensagem deve ter de 1 a 150 caracteres válidos';
 END IF;
 IF p_recipient IS NOT NULL THEN
  IF p_teacher_only THEN RAISE EXCEPTION 'Escolha apenas um destinatário';END IF;
  IF NOT coalesce(c.peer_messages,false) THEN
   RAISE EXCEPTION 'Mensagens direcionadas desativadas';END IF;
  SELECT rl.student_id INTO v_recipient
  FROM public.exam_lobby rl
  JOIN public.students s ON s.id=rl.student_id
  WHERE rl.exam_id=l.exam_id AND s.active
    AND substr(md5(rl.student_id::text),1,10)=p_recipient
  LIMIT 1;
  IF v_recipient IS NULL OR v_recipient=l.student_id OR NOT EXISTS(
   SELECT 1 FROM public.exam_lobby rl
   JOIN public.students s ON s.id=rl.student_id
   WHERE rl.exam_id=l.exam_id AND rl.student_id=v_recipient AND s.active
   AND rl.requested_at IS NOT NULL
   AND rl.last_seen_at>now()-interval '45 seconds'
   AND NOT EXISTS(SELECT 1 FROM public.attempts a
    WHERE a.exam_id=rl.exam_id AND a.student_id=rl.student_id)
  ) THEN RAISE EXCEPTION 'Destinatário indisponível';END IF;
 END IF;
 -- Lock serializes concurrent sends from same session: prevent 2 tabs
 -- bypassing the 3-second throttle. This lock also protects exam transition.
 PERFORM 1 FROM public.exam_lobby
 WHERE lobby_token=p_lobby_token FOR UPDATE;
 IF EXISTS(SELECT 1 FROM public.exam_lobby_chat_messages
  WHERE exam_id=l.exam_id AND sender_student_id=l.student_id
    AND created_at>now()-interval '3 seconds') THEN
    RAISE EXCEPTION 'Aguarde 3 segundos antes de enviar outra mensagem';
 END IF;
 INSERT INTO public.exam_lobby_chat_messages
 (exam_id,sender_student_id,recipient_student_id,teacher_only,body)
 VALUES (l.exam_id,l.student_id,v_recipient,coalesce(p_teacher_only,false),v_text) RETURNING id INTO v_id;
 RETURN jsonb_build_object('ok',true,'id',v_id);
END;
$fn$;

CREATE OR REPLACE FUNCTION public.teacher_lobby_chat_settings(
 p_exam_slug text,p_enabled boolean DEFAULT NULL,p_peer_messages boolean DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='public'
AS $fn$
DECLARE e public.exams;c public.exam_lobby_chat_settings;
BEGIN
 IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Acesso negado';END IF;
 SELECT * INTO e FROM public.exams WHERE slug=p_exam_slug;
 IF NOT FOUND THEN RAISE EXCEPTION 'Avaliação inexistente';END IF;
 IF p_enabled IS NOT NULL OR p_peer_messages IS NOT NULL THEN
  INSERT INTO public.exam_lobby_chat_settings(exam_id,enabled,peer_messages)
  VALUES(e.id,coalesce(p_enabled,false),coalesce(p_peer_messages,false))
  ON CONFLICT(exam_id) DO UPDATE SET
   enabled=coalesce(p_enabled,public.exam_lobby_chat_settings.enabled),
   peer_messages=coalesce(p_peer_messages,public.exam_lobby_chat_settings.peer_messages),
   updated_at=now();
 END IF;
 SELECT * INTO c FROM public.exam_lobby_chat_settings WHERE exam_id=e.id;
 RETURN jsonb_build_object('enabled',coalesce(c.enabled,false),
   'peer_messages',coalesce(c.peer_messages,false));
END;$fn$;

CREATE OR REPLACE FUNCTION public.teacher_lobby_chat_mute(
 p_exam_slug text,p_student_id uuid,p_muted boolean
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='public'
AS $fn$
DECLARE e public.exams;g public.exam_supervision;
BEGIN
 IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Acesso negado';END IF;
 SELECT * INTO e FROM public.exams WHERE slug=p_exam_slug;
 SELECT * INTO g FROM public.exam_supervision WHERE exam_id=e.id AND enabled;
 IF NOT FOUND OR NOT EXISTS(SELECT 1 FROM public.students s
 WHERE s.id=p_student_id AND s.class_group=g.class_group AND s.active)
 THEN RAISE EXCEPTION 'Aluno fora da turma supervisionada';END IF;
 INSERT INTO public.exam_lobby_chat_mutes(exam_id,student_id,muted)
 VALUES(e.id,p_student_id,p_muted)
 ON CONFLICT(exam_id,student_id) DO UPDATE SET muted=excluded.muted;
 RETURN jsonb_build_object('ok',true,'muted',p_muted);
END;$fn$;

CREATE OR REPLACE FUNCTION public.teacher_lobby_chat_read(
 p_exam_slug text,p_after bigint DEFAULT 0
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='public'
AS $fn$
DECLARE e public.exams;v_messages jsonb;
BEGIN
 IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Acesso negado';END IF;
 SELECT * INTO e FROM public.exams WHERE slug=p_exam_slug;
 IF NOT FOUND THEN RAISE EXCEPTION 'Avaliação inexistente';END IF;
 SELECT coalesce(jsonb_agg(to_jsonb(m) ORDER BY m.id),'[]'::jsonb)
 INTO v_messages FROM (
  SELECT c.id,c.body,c.created_at,c.teacher_sender,c.teacher_only,
    coalesce(s.name,'Professor') AS sender,
    coalesce(r.name,'Todos') AS recipient
  FROM public.exam_lobby_chat_messages c
  LEFT JOIN public.students s ON s.id=c.sender_student_id
  LEFT JOIN public.students r ON r.id=c.recipient_student_id
  WHERE c.exam_id=e.id AND c.id>greatest(0,coalesce(p_after,0))
  ORDER BY c.id DESC LIMIT 60
 ) m;
 RETURN jsonb_build_object('messages',v_messages);
END;$fn$;

CREATE OR REPLACE FUNCTION public.teacher_lobby_chat_send(
 p_exam_slug text,p_body text,p_recipient uuid DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='public'
AS $fn$
DECLARE e public.exams;g public.exam_supervision;v_id bigint;v_body text;
BEGIN
 IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Acesso negado';END IF;
 SELECT * INTO e FROM public.exams WHERE slug=p_exam_slug;
 SELECT * INTO g FROM public.exam_supervision WHERE exam_id=e.id AND enabled;
 IF NOT FOUND THEN RAISE EXCEPTION 'Supervisão não habilitada';END IF;
 v_body:=btrim(coalesce(p_body,''));
 IF char_length(v_body) NOT BETWEEN 1 AND 150 THEN
  RAISE EXCEPTION 'Mensagem deve ter de 1 a 150 caracteres';END IF;
 IF p_recipient IS NOT NULL AND NOT EXISTS(
  SELECT 1 FROM public.students WHERE id=p_recipient AND class_group=g.class_group AND active
 ) THEN RAISE EXCEPTION 'Destinatário inválido';END IF;
 INSERT INTO public.exam_lobby_chat_messages(exam_id,teacher_sender,recipient_student_id,body)
 VALUES(e.id,true,p_recipient,v_body) RETURNING id INTO v_id;
 RETURN jsonb_build_object('ok',true,'id',v_id);
END;$fn$;

